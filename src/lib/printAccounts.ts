import { formatNaira } from "@contracts/money";
import { getCachedBusinessSettings } from "@/lib/businessSettings";

const esc = (s: string | null | undefined) =>
  (s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const dayTime = (iso: string) =>
  `${new Date(iso).toLocaleDateString("en-NG", { day: "numeric", month: "short", year: "numeric" })} ${new Date(iso).toLocaleTimeString("en-NG", { hour: "2-digit", minute: "2-digit" })}`;

const BASE_CSS = `
  * { box-sizing: border-box; }
  body { font-family: "Helvetica Neue", Arial, sans-serif; color: #1a1a1a; margin: 32px; font-size: 12px; }
  h1 { font-size: 20px; margin: 0; letter-spacing: 0.06em; }
  .muted { color: #666; }
  .head { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 2px solid #1a1a1a; padding-bottom: 12px; }
  .head .biz { text-align: right; }
  .kpis { display: flex; gap: 12px; margin: 16px 0; flex-wrap: wrap; }
  .kpi { border: 1px solid #ddd; padding: 10px 14px; min-width: 130px; }
  .kpi b { display: block; font-size: 9px; text-transform: uppercase; letter-spacing: 0.1em; color: #666; margin-bottom: 3px; }
  .kpi span { font-size: 15px; font-weight: 700; }
  table { width: 100%; border-collapse: collapse; margin-top: 10px; }
  th { text-align: left; font-size: 10px; text-transform: uppercase; letter-spacing: 0.1em; color: #666; border-bottom: 1px solid #999; padding: 6px 8px; }
  td { padding: 6px 8px; vertical-align: top; border-bottom: 1px solid #eee; }
  .r { text-align: right; }
  .pos { color: #0a7a3d; } .neg { color: #b00020; }
  .foot { margin-top: 28px; padding-top: 10px; border-top: 1px solid #ccc; display: flex; justify-content: space-between; }
  @media print { body { margin: 12mm; } }
`;

const KIND_LABEL: Record<string, string> = {
  sale_payment: "Sale payment",
  expense: "Expense",
  transfer: "Transfer",
  money_in: "Money in",
  money_out: "Money out",
  adjustment: "Adjustment",
  credit_repayment: "Debt repayment",
  payroll: "Salary payment",
};

export interface PrintableAccount {
  id: number;
  code: string;
  name: string;
  balanceKobo: number;
  todayInKobo: number;
  todayOutKobo: number;
}

export interface PrintableTxRow {
  id: number;
  accountName: string;
  direction: "in" | "out";
  amountKobo: number;
  kind: string;
  refId: string | null;
  note: string | null;
  staffName: string | null;
  createdAt: string;
}

/** Account statement: balance cards + the filtered transaction table. */
export function printAccountStatement({
  accounts,
  rows,
  totalInKobo,
  totalOutKobo,
  filterLabel,
}: {
  accounts: PrintableAccount[];
  rows: PrintableTxRow[];
  totalInKobo: number;
  totalOutKobo: number;
  filterLabel: string;
}): boolean {
  const biz = getCachedBusinessSettings();
  const grand = accounts.reduce((s, a) => s + a.balanceKobo, 0);

  const body = `
  <div class="head">
    <div>
      <h1>Bank &amp; Cash Statement</h1>
      <div class="muted">${esc(filterLabel)} · generated ${dayTime(new Date().toISOString())}</div>
    </div>
    <div class="biz">
      <strong>${esc(biz?.businessName) || "Royal Bite Kitchen"}</strong><br/>
      ${biz?.businessAddress ? `${esc(biz.businessAddress)}<br/>` : ""}
      ${biz?.businessPhone ? esc(biz.businessPhone) : ""}
    </div>
  </div>

  <div class="kpis">
    ${accounts
      .map(
        (a) => `<div class="kpi"><b>${esc(a.name)}</b><span>${esc(formatNaira(a.balanceKobo))}</span></div>`,
      )
      .join("")}
    <div class="kpi"><b>Total held</b><span>${esc(formatNaira(grand))}</span></div>
  </div>

  <table>
    <thead>
      <tr><th>Date</th><th>Account</th><th>Type</th><th class="r">In</th><th class="r">Out</th><th>Details</th><th>By</th></tr>
    </thead>
    <tbody>
      ${rows
        .map(
          (r) => `<tr>
        <td>${esc(dayTime(r.createdAt))}</td>
        <td>${esc(r.accountName)}</td>
        <td>${esc(KIND_LABEL[r.kind] ?? r.kind)}</td>
        <td class="r pos">${r.direction === "in" ? esc(formatNaira(r.amountKobo)) : ""}</td>
        <td class="r neg">${r.direction === "out" ? esc(formatNaira(r.amountKobo)) : ""}</td>
        <td>${esc([r.refId, r.note].filter(Boolean).join(" · "))}</td>
        <td>${esc(r.staffName ?? "—")}</td>
      </tr>`,
        )
        .join("")}
    </tbody>
  </table>

  <div class="kpis">
    <div class="kpi"><b>Money in (filter)</b><span class="pos">${esc(formatNaira(totalInKobo))}</span></div>
    <div class="kpi"><b>Money out (filter)</b><span class="neg">${esc(formatNaira(totalOutKobo))}</span></div>
    <div class="kpi"><b>Net</b><span>${esc(formatNaira(totalInKobo - totalOutKobo))}</span></div>
  </div>

  <div class="foot">
    <span class="muted">${rows.length} transactions shown</span>
    <span class="muted">Generated by ${esc(biz?.businessName) || "Royal Bite Kitchen"} POS</span>
  </div>`;

  const html = `<!doctype html>
<html><head><meta charset="utf-8"/><title>Bank &amp; Cash Statement</title>
<style>${BASE_CSS}</style></head>
<body>${body}
<script>window.onload = () => { window.print(); };</script>
</body></html>`;
  const w = window.open("", "_blank", "width=900,height=1100");
  if (!w) return false;
  w.document.write(html);
  w.document.close();
  return true;
}
