import { formatNaira } from "@contracts/money";
import { formatQty, STOCK_MOVEMENT_LABEL } from "@contracts/stock";
import { getCachedBusinessSettings } from "@/lib/businessSettings";

const esc = (s: string | null | undefined) =>
  (s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const day = (iso: string) =>
  new Date(iso).toLocaleDateString("en-NG", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
const dayTime = (iso: string) =>
  `${day(iso)} ${new Date(iso).toLocaleTimeString("en-NG", { hour: "2-digit", minute: "2-digit" })}`;

const BASE_CSS = `
  * { box-sizing: border-box; }
  body { font-family: "Helvetica Neue", Arial, sans-serif; color: #1a1a1a; margin: 32px; font-size: 12px; }
  h1 { font-size: 20px; margin: 0; letter-spacing: 0.06em; }
  .muted { color: #666; }
  .head { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 2px solid #1a1a1a; padding-bottom: 12px; }
  .head .biz { text-align: right; }
  .kpis { display: flex; gap: 12px; margin: 16px 0; flex-wrap: wrap; }
  .kpi { border: 1px solid #ddd; padding: 10px 14px; min-width: 130px; }
  .kpi b { display: block; font-size: 9px; text-transform: uppercase; letter-spacing: 0.1em; color: #666; margin-bottom: 3px; }
  .kpi span { font-size: 15px; font-weight: 700; }
  table { width: 100%; border-collapse: collapse; margin-top: 10px; }
  th { text-align: left; font-size: 10px; text-transform: uppercase; letter-spacing: 0.1em; color: #666; border-bottom: 1px solid #999; padding: 6px 8px; }
  td { padding: 6px 8px; vertical-align: top; border-bottom: 1px solid #eee; }
  .r { text-align: right; }
  .low { color: #b26a00; font-weight: 700; }
  .out { color: #b00020; font-weight: 700; }
  .pos { color: #0a7a3d; } .neg { color: #b26a00; }
  .foot { margin-top: 28px; padding-top: 10px; border-top: 1px solid #ccc; display: flex; justify-content: space-between; }
  @media print { body { margin: 12mm; } }
`;

function openPrintWindow(title: string, body: string): boolean {
  const html = `<!doctype html>
<html><head><meta charset="utf-8"/><title>${esc(title)}</title>
<style>${BASE_CSS}</style></head>
<body>
${body}
<script>window.onload = () => { window.print(); };</script>
</body></html>`;
  const w = window.open("", "_blank", "width=900,height=1100");
  if (!w) return false;
  w.document.write(html);
  w.document.close();
  return true;
}

function bizHeader(title: string, subtitle: string): string {
  const biz = getCachedBusinessSettings();
  return `
  <div class="head">
    <div>
      <h1>${esc(title)}</h1>
      <div class="muted">${esc(subtitle)} · generated ${dayTime(new Date().toISOString())}</div>
    </div>
    <div class="biz">
      <strong>${esc(biz?.businessName) || "Royal Bite Kitchen"}</strong><br/>
      ${biz?.businessAddress ? `${esc(biz.businessAddress)}<br/>` : ""}
      ${biz?.businessPhone ? esc(biz.businessPhone) : ""}
    </div>
  </div>`;
}

function bizFooter(note: string): string {
  const biz = getCachedBusinessSettings();
  return `
  <div class="foot">
    <span class="muted">${esc(note)}</span>
    <span class="muted">Generated by ${esc(biz?.businessName) || "Royal Bite Kitchen"} POS</span>
  </div>`;
}

// ---------------------------------------------------------------- stock list

export interface PrintableStockRow {
  id: number;
  name: string;
  unit: string;
  quantityMilli: number;
  lowStockAtMilli: number | null;
  costPerUnitKobo: number | null;
  active: boolean;
  low: boolean;
  lastMovementAt: string | null;
}

/** Print the stock list exactly as filtered on screen (search / low-only). */
export function printStockList(
  rows: PrintableStockRow[],
  opts: { search?: string; lowOnly?: boolean },
): boolean {
  const filterNote = [
    opts.search ? `search "${opts.search}"` : null,
    opts.lowOnly ? "low stock only" : null,
  ]
    .filter(Boolean)
    .join(" · ");

  const body = `
  ${bizHeader("STOCK REPORT", filterNote ? `Filtered: ${filterNote}` : "All items")}
  <table>
    <thead><tr>
      <th style="width:30%">Item</th><th>Unit</th>
      <th class="r">On hand</th><th class="r">Alert at</th>
      <th class="r">Cost / unit</th><th class="r">Stock value</th><th>Status</th>
    </tr></thead>
    <tbody>
      ${rows
        .map((r) => {
          const value =
            r.costPerUnitKobo !== null && r.quantityMilli > 0
              ? Math.round((r.quantityMilli * r.costPerUnitKobo) / 1000)
              : null;
          const status = !r.active
            ? "Deactivated"
            : r.quantityMilli <= 0
              ? "OUT OF STOCK"
              : r.low
                ? "LOW"
                : "OK";
          const cls = !r.active ? "muted" : r.quantityMilli <= 0 ? "out" : r.low ? "low" : "";
          return `<tr>
            <td><strong>${esc(r.name)}</strong><br/><span class="muted">${r.lastMovementAt ? `last move ${dayTime(r.lastMovementAt)}` : "no movements yet"}</span></td>
            <td>${esc(r.unit)}</td>
            <td class="r">${formatQty(r.quantityMilli)}</td>
            <td class="r">${r.lowStockAtMilli !== null ? formatQty(r.lowStockAtMilli) : "—"}</td>
            <td class="r">${r.costPerUnitKobo !== null ? formatNaira(r.costPerUnitKobo) : "—"}</td>
            <td class="r">${value !== null ? formatNaira(value) : "—"}</td>
            <td class="${cls}">${status}</td>
          </tr>`;
        })
        .join("")}
    </tbody>
  </table>
  ${bizFooter(`${rows.length} item${rows.length === 1 ? "" : "s"}${filterNote ? ` · ${filterNote}` : ""}`)}`;
  return openPrintWindow("Stock report", body);
}

// -------------------------------------------------------------- stock card

export interface PrintableStockCard {
  item: {
    name: string;
    unit: string;
    quantityMilli: number;
    lowStockAtMilli: number | null;
    costPerUnitKobo: number | null;
    active: boolean;
    createdAt: string;
    createdByName: string | null;
    stockValueKobo: number;
  };
  totals: {
    restockedMilli: number;
    usageMilli: number;
    wasteMilli: number;
    adjustmentNetMilli: number;
    spendKobo: number;
  };
  movements: Array<{
    id: number;
    type: string;
    deltaMilli: number;
    balanceAfterMilli: number;
    totalCostKobo: number | null;
    note: string | null;
    createdAt: string;
    staffName: string | null;
  }>;
  total: number;
  filterNote: string;
}

/** Print one item's stock card: header, KPI strip and the filtered ledger. */
export function printStockCard(card: PrintableStockCard): boolean {
  const it = card.item;
  const u = it.unit;
  const signed = (milli: number) =>
    `${milli >= 0 ? "+" : "−"}${formatQty(Math.abs(milli))} ${u}`;

  const body = `
  ${bizHeader("STOCK CARD", it.name)}
  <p style="margin:12px 0 0">
    <strong style="font-size:16px">${esc(it.name)}</strong>
    <span class="muted"> · counted in ${esc(u)}${it.active ? "" : " · DEACTIVATED"}</span><br/>
    <span class="muted">Added ${day(it.createdAt)}${it.createdByName ? ` by ${esc(it.createdByName)}` : ""}</span>
  </p>
  <div class="kpis">
    <div class="kpi"><b>On hand</b><span class="${it.quantityMilli <= 0 ? "out" : it.lowStockAtMilli !== null && it.quantityMilli <= it.lowStockAtMilli ? "low" : ""}">${formatQty(it.quantityMilli)} ${esc(u)}</span></div>
    <div class="kpi"><b>Stock value</b><span>${formatNaira(it.stockValueKobo)}</span></div>
    <div class="kpi"><b>Alert at</b><span>${it.lowStockAtMilli !== null ? `${formatQty(it.lowStockAtMilli)} ${esc(u)}` : "—"}</span></div>
    <div class="kpi"><b>Restocked</b><span class="pos">+${formatQty(card.totals.restockedMilli)} ${esc(u)}</span></div>
    <div class="kpi"><b>Used</b><span class="neg">−${formatQty(card.totals.usageMilli)} ${esc(u)}</span></div>
    <div class="kpi"><b>Wasted</b><span class="neg">−${formatQty(card.totals.wasteMilli)} ${esc(u)}</span></div>
    <div class="kpi"><b>Adjustments</b><span>${signed(card.totals.adjustmentNetMilli)}</span></div>
    <div class="kpi"><b>Restock spend</b><span>${formatNaira(card.totals.spendKobo)}</span></div>
  </div>
  <p class="muted" style="margin:0">Movement ledger — ${esc(card.filterNote)} · ${card.total} movement${card.total === 1 ? "" : "s"}${card.movements.length < card.total ? ` (first ${card.movements.length} shown)` : ""}</p>
  <table>
    <thead><tr>
      <th style="width:20%">Date</th><th>Type</th><th class="r">Change</th>
      <th class="r">Balance</th><th class="r">Cost</th><th>By</th><th style="width:24%">Note</th>
    </tr></thead>
    <tbody>
      ${card.movements
        .map(
          (m) => `<tr>
        <td>${dayTime(m.createdAt)}</td>
        <td>${STOCK_MOVEMENT_LABEL[m.type] ?? esc(m.type)}</td>
        <td class="r ${m.deltaMilli >= 0 ? "pos" : "neg"}">${m.deltaMilli >= 0 ? "+" : "−"}${formatQty(Math.abs(m.deltaMilli))} ${esc(u)}</td>
        <td class="r">${formatQty(m.balanceAfterMilli)} ${esc(u)}</td>
        <td class="r">${m.totalCostKobo !== null ? formatNaira(m.totalCostKobo) : "—"}</td>
        <td>${esc(m.staffName) || "—"}</td>
        <td>${esc(m.note) || "—"}</td>
      </tr>`,
        )
        .join("")}
    </tbody>
  </table>
  ${bizFooter(`${it.name} · stock card`)}`;
  return openPrintWindow(`Stock card — ${it.name}`, body);
}
