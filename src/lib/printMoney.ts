import { formatNaira } from "@contracts/money";
import { getCachedBusinessSettings } from "@/lib/businessSettings";

const esc = (s: string | null | undefined) =>
  (s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const day = (iso: string) =>
  new Date(iso).toLocaleDateString("en-NG", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
const dayTime = (iso: string) =>
  `${day(iso)} ${new Date(iso).toLocaleTimeString("en-NG", { hour: "2-digit", minute: "2-digit" })}`;

const BASE_CSS = `
  * { box-sizing: border-box; }
  body { font-family: "Helvetica Neue", Arial, sans-serif; color: #1a1a1a; margin: 32px; font-size: 12px; }
  h1 { font-size: 20px; margin: 0; letter-spacing: 0.06em; }
  .muted { color: #666; }
  .head { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 2px solid #1a1a1a; padding-bottom: 12px; }
  .head .biz { text-align: right; }
  .kpis { display: flex; gap: 12px; margin: 16px 0; flex-wrap: wrap; }
  .kpi { border: 1px solid #ddd; padding: 10px 14px; min-width: 130px; }
  .kpi b { display: block; font-size: 9px; text-transform: uppercase; letter-spacing: 0.1em; color: #666; margin-bottom: 3px; }
  .kpi span { font-size: 15px; font-weight: 700; }
  table { width: 100%; border-collapse: collapse; margin-top: 10px; }
  th { text-align: left; font-size: 10px; text-transform: uppercase; letter-spacing: 0.1em; color: #666; border-bottom: 1px solid #999; padding: 6px 8px; }
  td { padding: 6px 8px; vertical-align: top; border-bottom: 1px solid #eee; }
  .r { text-align: right; }
  .warn { color: #b26a00; font-weight: 700; }
  .bad { color: #b00020; font-weight: 700; }
  .good { color: #0a7a3d; font-weight: 700; }
  .foot { margin-top: 28px; padding-top: 10px; border-top: 1px solid #ccc; display: flex; justify-content: space-between; }
  @media print { body { margin: 12mm; } }
`;

function openPrintWindow(title: string, body: string): boolean {
  const html = `<!doctype html>
<html><head><meta charset="utf-8"/><title>${esc(title)}</title>
<style>${BASE_CSS}</style></head>
<body>
${body}
<script>window.onload = () => { window.print(); };</script>
</body></html>`;
  const w = window.open("", "_blank", "width=900,height=1100");
  if (!w) return false;
  w.document.write(html);
  w.document.close();
  return true;
}

function bizHeader(title: string, subtitle: string): string {
  const biz = getCachedBusinessSettings();
  return `
  <div class="head">
    <div>
      <h1>${esc(title)}</h1>
      <div class="muted">${esc(subtitle)} · generated ${dayTime(new Date().toISOString())}</div>
    </div>
    <div class="biz">
      <strong>${esc(biz?.businessName) || "Royal Bite Kitchen"}</strong><br/>
      ${biz?.businessAddress ? `${esc(biz.businessAddress)}<br/>` : ""}
      ${biz?.businessPhone ? esc(biz.businessPhone) : ""}
    </div>
  </div>`;
}

function bizFooter(note: string): string {
  const biz = getCachedBusinessSettings();
  return `
  <div class="foot">
    <span class="muted">${esc(note)}</span>
    <span class="muted">Generated by ${esc(biz?.businessName) || "Royal Bite Kitchen"} POS</span>
  </div>`;
}

// ------------------------------------------------------------- cash drawer

export interface PrintableDrawerSummary {
  cashSalesKobo: number;
  cashRepaymentsKobo: number;
  cashExpensesKobo: number;
  expectedKobo: number;
}

export interface PrintableDrawerCount {
  countId: number;
  countedKobo: number;
  expectedKobo: number;
  diffKobo: number;
  note: string | null;
  staffName: string | null;
  countedAt: string;
}

export function printDrawerSheet(
  summary: PrintableDrawerSummary,
  counts: PrintableDrawerCount[],
  rangeLabel: string,
): boolean {
  const kpi = (label: string, value: string, cls = "") =>
    `<div class="kpi"><b>${esc(label)}</b><span class="${cls}">${esc(value)}</span></div>`;
  const rows = counts
    .map(
      (c) => `<tr>
        <td>${esc(dayTime(c.countedAt))}</td>
        <td>${esc(c.staffName ?? "—")}</td>
        <td class="r">${esc(formatNaira(c.countedKobo))}</td>
        <td class="r">${esc(formatNaira(c.expectedKobo))}</td>
        <td class="r ${c.diffKobo === 0 ? "good" : "bad"}">${c.diffKobo === 0 ? "balanced" : `${c.diffKobo > 0 ? "+" : "−"}${esc(formatNaira(Math.abs(c.diffKobo)))}`}</td>
        <td>${esc(c.note ?? "")}</td>
      </tr>`,
    )
    .join("");
  return openPrintWindow(
    `Cash drawer — ${rangeLabel}`,
    `${bizHeader("Cash drawer report", rangeLabel)}
    <div class="kpis">
      ${kpi("Cash sales", formatNaira(summary.cashSalesKobo))}
      ${kpi("Cash repayments", formatNaira(summary.cashRepaymentsKobo))}
      ${kpi("Cash expenses", `−${formatNaira(summary.cashExpensesKobo)}`, "bad")}
      ${kpi("Expected in drawer", formatNaira(summary.expectedKobo), "good")}
    </div>
    <h1 style="font-size:13px;margin-top:18px">Drawer counts</h1>
    <table>
      <thead><tr><th>Counted at</th><th>By</th><th class="r">Counted</th><th class="r">Expected</th><th class="r">Difference</th><th>Note</th></tr></thead>
      <tbody>${rows || `<tr><td colspan="6" class="muted">No counts recorded in this period.</td></tr>`}</tbody>
    </table>
    ${bizFooter(`${counts.length} count${counts.length === 1 ? "" : "s"} shown`)}`,
  );
}

// --------------------------------------------------------------- expenses

export interface PrintableExpense {
  expenseId: number;
  category: string;
  amountKobo: number;
  note: string;
  method: string;
  staffName: string | null;
  expenseAt: string;
  status: string;
  voidedAt: string | null;
}

export function printExpenses(
  rows: PrintableExpense[],
  opts: { filterLabel: string; approvedTotalKobo: number; total: number },
): boolean {
  const bodyRows = rows
    .map((e) => {
      const state = e.voidedAt ? "Voided" : e.status === "approved" ? "Approved" : e.status === "pending" ? "Pending" : "Rejected";
      const cls = e.voidedAt || e.status === "rejected" ? "bad" : e.status === "pending" ? "warn" : "good";
      return `<tr>
        <td>${esc(dayTime(e.expenseAt))}</td>
        <td>${esc(e.note)}</td>
        <td>${esc(e.category)}</td>
        <td>${esc(e.method.replace("_", " "))}</td>
        <td>${esc(e.staffName ?? "—")}</td>
        <td class="${cls}">${state}</td>
        <td class="r">${esc(formatNaira(e.amountKobo))}</td>
      </tr>`;
    })
    .join("");
  return openPrintWindow(
    `Expenses — ${opts.filterLabel}`,
    `${bizHeader("Expenses report", opts.filterLabel)}
    <div class="kpis">
      <div class="kpi"><b>Expenses shown</b><span>${rows.length} of ${opts.total}</span></div>
      <div class="kpi"><b>Approved total</b><span class="good">${esc(formatNaira(opts.approvedTotalKobo))}</span></div>
    </div>
    <table>
      <thead><tr><th>Date</th><th>Note</th><th>Category</th><th>Paid via</th><th>By</th><th>Status</th><th class="r">Amount</th></tr></thead>
      <tbody>${bodyRows || `<tr><td colspan="7" class="muted">No expenses match these filters.</td></tr>`}</tbody>
    </table>
    ${bizFooter(opts.filterLabel)}`,
  );
}

// -------------------------------------------------------------- terminals

export interface PrintableTerminalStat {
  id: number;
  name: string;
  provider: string | null;
  active: boolean;
  payments: number;
  totalKobo: number;
}

export function printTerminalTakings(
  terminals: PrintableTerminalStat[],
  unassigned: { payments: number; totalKobo: number },
  rangeLabel: string,
): boolean {
  const grand = terminals.reduce((s, t) => s + t.totalKobo, 0) + unassigned.totalKobo;
  const rows = terminals
    .map(
      (t) => `<tr>
        <td>${esc(t.name)}${t.active ? "" : ' <span class="muted">(disabled)</span>'}</td>
        <td>${esc(t.provider ?? "—")}</td>
        <td class="r">${t.payments}</td>
        <td class="r">${esc(formatNaira(t.totalKobo))}</td>
      </tr>`,
    )
    .join("");
  return openPrintWindow(
    `Terminal takings — ${rangeLabel}`,
    `${bizHeader("Card takings by terminal", rangeLabel)}
    <div class="kpis">
      <div class="kpi"><b>Total card takings</b><span class="good">${esc(formatNaira(grand))}</span></div>
      <div class="kpi"><b>Terminals</b><span>${terminals.length}</span></div>
    </div>
    <table>
      <thead><tr><th>Terminal</th><th>Provider</th><th class="r">Payments</th><th class="r">Total</th></tr></thead>
      <tbody>
        ${rows}
        <tr><td colspan="2" class="muted">Not assigned to a terminal</td><td class="r">${unassigned.payments}</td><td class="r muted">${esc(formatNaira(unassigned.totalKobo))}</td></tr>
        <tr><td colspan="2"><strong>Total</strong></td><td class="r"><strong>${terminals.reduce((s, t) => s + t.payments, 0) + unassigned.payments}</strong></td><td class="r"><strong>${esc(formatNaira(grand))}</strong></td></tr>
      </tbody>
    </table>
    ${bizFooter(rangeLabel)}`,
  );
}
